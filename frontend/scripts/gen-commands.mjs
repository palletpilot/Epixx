import { compile } from "json-schema-to-typescript";
import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontendRoot = join(here, "..");
const commandsDir = join(frontendRoot, "..", "contracts", "commands");
const outFile = join(frontendRoot, "packages", "domain", "src", "generated", "commands.ts");

const chunks = ["// Generated by scripts/gen-commands.mjs. Do not edit.", ""];

for (const typeName of (await readdir(commandsDir)).sort()) {
  const dir = join(commandsDir, typeName);
  if (!(await stat(dir)).isDirectory()) {
    continue;
  }
  const versions = (await readdir(dir))
    .filter((name) => /^v\d+\.json$/.test(name))
    .sort((a, b) => Number(a.slice(1, -5)) - Number(b.slice(1, -5)));
  for (const file of versions) {
    const raw = await readFile(join(dir, file), "utf8");
    const parsed = JSON.parse(raw.replace(/^\uFEFF/, ""));
    const ident = `${typeName}${file.slice(0, -5).toUpperCase()}`;
    const schema = { ...parsed, title: ident };
    delete schema.$id;
    const ts = await compile(schema, ident, {
      bannerComment: "",
      additionalProperties: true,
      cwd: dir,
    });
    chunks.push(ts.trimEnd(), "");
  }
}

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, chunks.join("\n") + "\n");
console.log(`Wrote ${outFile}`);
